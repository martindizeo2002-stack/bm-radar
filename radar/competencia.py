"""Competencia profunda: YouTube (videos + shorts con subtítulos) y anuncios de Meta Ad Library vía Apify.
Guarda en data/competencia/<handle>/{yt.jsonl, ads.json}. No toca todas.jsonl (que es solo Instagram)."""
from __future__ import annotations
import json, urllib.parse
from . import config, apify

COMP = config.DATA / "competencia"
COMP.mkdir(parents=True, exist_ok=True)

CANALES = {
    "woker.oficial": {"yt": "https://www.youtube.com/channel/UCZNdTdFM-wZ-A4lAXlyjOpQ", "ads_q": ["Woker Achiever", "Woker"], "ads_match": ["woker"]},
    "nicolorenzonn": {"yt": "https://www.youtube.com/channel/UCbo7ggRqpZJChwKSrMj-phg", "ads_q": ["Nico Lorenzon"], "ads_match": ["lorenzon"]},
    "matelezama": {"yt": "https://www.youtube.com/@matelezama", "ads_q": ["Mateo Lezama", "Vertice ecommerce"], "ads_match": ["lezama", "vertice", "vértice"]},
}


def carpeta(handle: str):
    c = COMP / handle
    c.mkdir(parents=True, exist_ok=True)
    return c


def _txt_subs(it: dict) -> str:
    subs = it.get("subtitles") or []
    if isinstance(subs, list):
        for s in subs:
            for k in ("plaintext", "srt", "vtt", "text"):
                if isinstance(s, dict) and s.get(k):
                    return str(s[k])[:30000]
    if isinstance(subs, str):
        return subs[:30000]
    return ""


def _norm_yt(it: dict, handle: str) -> dict | None:
    vid = it.get("id") or (it.get("url") or "").split("v=")[-1].split("&")[0]
    if not vid:
        return None
    url = it.get("url") or f"https://www.youtube.com/watch?v={vid}"
    es_short = "/shorts/" in url or (it.get("type") or "").lower() == "shorts"
    dur = it.get("duration")
    if isinstance(dur, str) and ":" in dur:
        seg = 0
        for x in dur.split(":"):
            seg = seg * 60 + int(x or 0)
        dur = seg
    return {
        "id": f"yt_{vid}", "plataforma": "yt", "cuenta": handle, "url": url,
        "tipo_media": "short" if es_short else "video",
        "fecha": (it.get("date") or it.get("uploadDate") or "")[:19],
        "caption": ((it.get("title") or "") + "\n\n" + (it.get("text") or it.get("description") or ""))[:3000],
        "titulo": it.get("title"), "views": it.get("viewCount"), "likes": it.get("likes"),
        "comentarios": it.get("commentsCount"), "duracion": dur,
        "thumb": it.get("thumbnailUrl"), "transcript": _txt_subs(it),
    }


def yt(handle: str, max_videos: int = 500, max_shorts: int = 400) -> list[dict]:
    c = CANALES[handle]
    entrada = {"startUrls": [{"url": c["yt"]}], "maxResults": max_videos, "maxResultsShorts": max_shorts, "maxResultStreams": 0,
               "transcriptionAndSubtitle": "ALWAYS_SUBTITLES", "subtitlesLanguage": "es", "subtitlesFormat": "plaintext",
               "preferAutoGeneratedSubtitles": True, "sortVideosBy": "NEWEST"}
    items = apify.correr("streamers~youtube-scraper", entrada, timeout_s=3600, tag=f"yt-{handle}")
    piezas = [p for p in (_norm_yt(i, handle) for i in items) if p]
    path = carpeta(handle) / "yt.jsonl"
    prev = {p["id"]: p for p in config.leer_jsonl(path)}
    for p in piezas:
        viejo = prev.get(p["id"], {})
        if viejo.get("analisis"):
            p["analisis"] = viejo["analisis"]
        prev[p["id"]] = p
    config.escribir_jsonl(path, list(prev.values()))
    con_t = sum(1 for p in piezas if p.get("transcript"))
    print(f"[yt] @{handle}: {len(piezas)} piezas ({sum(1 for p in piezas if p['tipo_media']=='short')} shorts) · con subtítulos {con_t}")
    return piezas


def ads(handle: str, count: int = 400) -> list[dict]:
    c = CANALES[handle]
    urls = [{"url": "https://www.facebook.com/ads/library/?" + urllib.parse.urlencode(
        {"active_status": "all", "ad_type": "all", "country": "ALL", "q": q, "search_type": "keyword_unordered", "media_type": "all"})}
        for q in c["ads_q"]]
    items = apify.correr("curious_coder~facebook-ads-library-scraper", {"urls": urls, "count": count, "scrapeAdDetails": False}, timeout_s=1800, tag=f"ads-{handle}")
    out = []
    for it in items:
        snap = it.get("snapshot") or {}
        pagina = it.get("page_name") or snap.get("page_name") or ""
        if not any(m in (pagina or "").lower() for m in c["ads_match"]):
            continue
        body = (snap.get("body") or {}).get("text") if isinstance(snap.get("body"), dict) else snap.get("body")
        cards = snap.get("cards") or []
        out.append({
            "id": f"ad_{it.get('ad_archive_id') or it.get('adArchiveID') or it.get('id')}",
            "pagina": pagina, "activo": it.get("is_active"),
            "desde": it.get("start_date_formatted") or it.get("start_date"), "hasta": it.get("end_date_formatted") or it.get("end_date"),
            "plataformas": it.get("publisher_platform"),
            "texto": (body or (cards[0].get("body") if cards and isinstance(cards[0], dict) else "") or "")[:3000],
            "titulo": snap.get("title") or (cards[0].get("title") if cards and isinstance(cards[0], dict) else None),
            "cta": snap.get("cta_text"), "link": snap.get("link_url"),
            "formato": snap.get("display_format"), "n_cards": len(cards),
            "url": f"https://www.facebook.com/ads/library/?id={it.get('ad_archive_id') or it.get('adArchiveID')}",
        })
    (carpeta(handle) / "ads.json").write_text(json.dumps(out, ensure_ascii=False, indent=1))
    print(f"[ads] @{handle}: {len(items)} crudos · {len(out)} de la página ({sum(1 for a in out if a.get('activo'))} activos)")
    return out


def corpus(handle: str) -> dict:
    """Un JSON por competidor con todo: IG (historia completa), YouTube, anuncios y perfil. Lo leen los analistas del dossier."""
    from . import cuenta
    ig = cuenta.piezas_de(handle)
    campos = ["id", "url", "tipo_media", "fecha", "caption", "likes", "comentarios", "views", "duracion", "fijado",
              "transcript", "idioma", "slides_texto", "lectura", "analisis"]
    ig_out = [{k: p.get(k) for k in campos if p.get(k) is not None} for p in ig]
    ytp = config.leer_jsonl(carpeta(handle) / "yt.jsonl")
    ads_p = carpeta(handle) / "ads.json"
    ads_l = json.loads(ads_p.read_text()) if ads_p.exists() else []
    perf = json.loads((config.DATA / "perfiles.json").read_text()).get(handle, {}) if (config.DATA / "perfiles.json").exists() else {}
    out = {"handle": handle, "generado": config.ahora().isoformat(timespec="seconds"), "perfil": perf,
           "instagram": ig_out, "youtube": ytp, "ads": ads_l,
           "cobertura": {"ig_piezas": len(ig_out), "ig_reels": sum(1 for p in ig_out if p.get("tipo_media") == "reel"),
                         "ig_carruseles": sum(1 for p in ig_out if p.get("tipo_media") == "carrusel"),
                         "ig_con_transcript": sum(1 for p in ig_out if p.get("transcript")),
                         "ig_con_slides": sum(1 for p in ig_out if p.get("slides_texto")),
                         "ig_analizadas": sum(1 for p in ig_out if p.get("analisis")),
                         "ig_desde": min((p.get("fecha") or "9") for p in ig_out)[:10] if ig_out else None,
                         "yt_piezas": len(ytp), "yt_con_transcript": sum(1 for p in ytp if p.get("transcript")),
                         "yt_analizadas": sum(1 for p in ytp if p.get("analisis")), "ads": len(ads_l)}}
    (carpeta(handle) / "corpus.json").write_text(json.dumps(out, ensure_ascii=False))
    print(f"[corpus] @{handle}: {json.dumps(out['cobertura'], ensure_ascii=False)}")
    return out


def analizar_yt(handle: str, hilos: int = 5, max_n: int = 64) -> int:
    """Analiza los videos de YouTube con el mismo esquema que IG y guarda en yt.jsonl (no toca todas.jsonl)."""
    from . import analizar
    path = carpeta(handle) / "yt.jsonl"
    ps = config.leer_jsonl(path)
    pend = [p for p in ps if not (p.get("analisis") or {}).get("tipo_angulo")]
    if not pend:
        return 0
    pend = pend[:max_n]  # por tandas: se persiste al final de cada llamada (los procesos largos en background se cortan)
    for p in pend:
        p["tipo_media"] = p.get("tipo_media") or "video"
    analizar.piezas(pend, forzar=True, hilos=hilos)  # persiste en todas.jsonl solo si el id existe (no existe): queda en memoria
    idx = {p["id"]: p for p in pend}
    for p in ps:
        if p["id"] in idx and idx[p["id"]].get("analisis"):
            p["analisis"] = idx[p["id"]]["analisis"]
    config.escribir_jsonl(path, ps)
    print(f"[yt] @{handle}: {sum(1 for p in pend if p.get('analisis'))}/{len(pend)} analizados")
    return len(pend)
